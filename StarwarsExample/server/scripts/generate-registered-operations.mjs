import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {
  buildSchema,
  parse,
  stripIgnoredCharacters,
  validate,
} from "graphql";

const operationsDirectory = fileURLToPath(
  new URL(
    "../../client/Packages/GraphQL/Source/Operations/",
    import.meta.url,
  ),
);
const outputPath = fileURLToPath(
  new URL("../src/registered-operations.generated.ts", import.meta.url),
);
const schemaPath = fileURLToPath(
  new URL("../src/schema.graphql", import.meta.url),
);

const schema = buildSchema(await readFile(schemaPath, "utf8"));
const operationFileNames = (await readdir(operationsDirectory))
  .filter((fileName) => fileName.endsWith(".graphql"))
  .sort();

const entries = [];
for (const fileName of operationFileNames) {
  const source = await readFile(`${operationsDirectory}/${fileName}`, "utf8");
  const errors = validate(schema, parse(source));
  if (errors.length > 0) {
    throw new Error(
      `${fileName} is invalid:\n${errors.map((error) => error.message).join("\n")}`,
    );
  }

  const document = stripIgnoredCharacters(source);
  const hash = createHash("sha256").update(document).digest("hex");
  entries.push({ document, fileName, hash });
}

const properties = entries
  .map(
    ({ document, fileName, hash }) =>
      `  // ${fileName}\n  ${JSON.stringify(hash)}: ${JSON.stringify(document)},`,
  )
  .join("\n");

const output = `// Generated by scripts/generate-registered-operations.mjs. Do not edit.\nexport const registeredOperations: Readonly<Record<string, string>> = {\n${properties}\n};\n`;

await writeFile(outputPath, output);
